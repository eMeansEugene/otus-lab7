#ifndef BULK_COMMAND_ACCUMULATOR_H
#define BULK_COMMAND_ACCUMULATOR_H

#include <memory>

#include "i_observer.h"

/**
 * @brief Накопитель команд, реализующий логику формирования блоков.
 *
 * Поддерживает два режима формирования блоков:
 *  - статический: блок закрывается по достижении N команд;
 *  - динамический: блок открывается командой "{" и закрывается
 *    парной командой "}", вложенные скобки увеличивают/уменьшают
 *    глубину вложенности, но не создают новых блоков.
 *
 * Accumulator не знает, как готовый блок выводится или сохраняется —
 * он только уведомляет подписанных наблюдателей (см. IObserver).
 */
class Accumulator {
public:
    /**
     * @brief Создаёт накопитель с заданным размером статического блока.
     * @param N Количество команд в статическом блоке. Должно быть больше 0.
     */
    explicit Accumulator(size_t N);

    /**
     * @brief Подписывает наблюдателя на события завершения блока.
     * @param os Наблюдатель, уведомляемый при готовности блока.
     */
    void AddObserver(const std::shared_ptr<IObserver>& os);

    /**
     * @brief Обрабатывает одну входную команду.
     *
     * Строки "{" и "}" трактуются как управляющие команды
     * динамического блока, остальные — как обычные команды.
     * @param command Строка команды (без символа перевода строки).
     */
    void ProcessCommand(const std::string& command);

    /**
     * @brief Сигнализирует о завершении входного потока данных.
     *
     * Если накопитель находится вне динамического блока — незавершённый
     * статический блок принудительно уведомляется. Если EOF наступил
     * внутри динамического блока (глубина > 0) — весь текущий
     * динамический блок отбрасывается без уведомления наблюдателей,
     * согласно требованиям задания.
     */
    void HandleEof();

private:
    /// Обрабатывает открывающую скобку "{": увеличивает глубину вложенности,
    /// при входе в динамический режим принудительно завершает текущий
    /// статический блок.
    void HandleOpenBrace();

    /// Обрабатывает закрывающую скобку "}": уменьшает глубину вложенности,
    /// при выходе из динамического режима (глубина == 0) уведомляет
    /// наблюдателей о готовом блоке.
    void HandleCloseBrace();

    /// Добавляет обычную команду в текущий блок; в статическом режиме
    /// проверяет достижение размера блока и уведомляет наблюдателей.
    void HandleCommand(const std::string& command);

    /// Уведомляет всех подписанных наблюдателей о текущем накопленном блоке.
    void NotifyObservers() const;

    /// Принудительно завершает текущий статический блок, если он не пуст.
    void FlushStaticBlockIfAny();

    std::vector<std::shared_ptr<IObserver> > observers_;
    time_t block_start_time_ {0};   ///< Время получения первой команды текущего блока.
    int dynamic_depth_{0};          ///< Глубина вложенности динамических блоков (0 — статический режим).
    size_t block_size_{0};          ///< Размер статического блока (N).
    std::vector<std::string> current_block_; ///< Команды текущего накапливаемого блока.
};

#endif //BULK_COMMAND_ACCUMULATOR_H
